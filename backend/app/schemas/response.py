"""Response Recommendation & Execution Schema for ORION v2 — Phase 6."""

from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional
from uuid import uuid4
from pydantic import BaseModel, ConfigDict, Field


class ActionCategory(str, Enum):
    BLOCK = "BLOCK"
    WARN = "WARN"
    AUTHENTICATION = "AUTHENTICATION"
    SESSION = "SESSION"
    VERIFICATION = "VERIFICATION"
    NOTIFICATION = "NOTIFICATION"
    INVESTIGATION = "INVESTIGATION"
    CONTAINMENT = "CONTAINMENT"
    ESCALATION = "ESCALATION"
    REPORTING = "REPORTING"


class ActionPriority(str, Enum):
    P0_IMMEDIATE = "P0_IMMEDIATE"
    P1_HIGH = "P1_HIGH"
    P2_MEDIUM = "P2_MEDIUM"
    P3_ADVISORY = "P3_ADVISORY"


class ActionExecutionMode(str, Enum):
    """
    ADVISORY  — No external system is touched. Analyst must act manually.
    SIMULATED — Execution is simulated within ORION only. Zero external impact guaranteed.
    """
    ADVISORY = "ADVISORY"
    SIMULATED = "SIMULATED"


class ResponseActionStatus(str, Enum):
    """Canonical state machine for a single response action lifecycle."""
    RECOMMENDED = "RECOMMENDED"       # Generated by playbook engine, not yet seen
    ACKNOWLEDGED = "ACKNOWLEDGED"     # Analyst has reviewed this action
    EXECUTING = "EXECUTING"           # Action has been dispatched (simulated)
    COMPLETED = "COMPLETED"           # Execution confirmed complete
    DISMISSED = "DISMISSED"           # Analyst explicitly dismissed
    FAILED = "FAILED"                 # Execution failed (simulation error)


# Valid state-machine transitions enforced on the backend
VALID_ACTION_TRANSITIONS: Dict[ResponseActionStatus, set] = {
    ResponseActionStatus.RECOMMENDED: {
        ResponseActionStatus.ACKNOWLEDGED,
        ResponseActionStatus.DISMISSED,
    },
    ResponseActionStatus.ACKNOWLEDGED: {
        ResponseActionStatus.EXECUTING,
        ResponseActionStatus.DISMISSED,
    },
    ResponseActionStatus.EXECUTING: {
        ResponseActionStatus.COMPLETED,
        ResponseActionStatus.FAILED,
    },
    ResponseActionStatus.COMPLETED: set(),    # terminal
    ResponseActionStatus.DISMISSED: {
        ResponseActionStatus.RECOMMENDED,     # re-open allowed
    },
    ResponseActionStatus.FAILED: {
        ResponseActionStatus.ACKNOWLEDGED,    # retry path
    },
}


class ResponseAuditEvent(BaseModel):
    """Immutable, append-only audit record for a single state transition or outcome."""
    id: str = Field(default_factory=lambda: f"audit_{uuid4().hex[:10]}")
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    action_id: str = Field(description="ID of the ResponseExecutionRecord this event belongs to")
    incident_id: str = Field(description="Parent incident ID")
    from_status: Optional[str] = Field(default=None)
    to_status: str
    actor: str = Field(default="SYSTEM", description="Who triggered this: analyst id or SYSTEM")
    mode: ActionExecutionMode = Field(default=ActionExecutionMode.ADVISORY)
    note: Optional[str] = Field(default=None, description="Optional analyst note for this transition")
    simulation_result: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Structured simulation output — guaranteed to have no real external side-effects"
    )

    model_config = ConfigDict(use_enum_values=True)


class ResponseExecutionRecord(BaseModel):
    """
    Full lifecycle record for one dispatched response action tied to an incident.
    This is the Phase 6 canonical response unit stored in the DB.
    """
    id: str = Field(default_factory=lambda: f"resp_{uuid4().hex[:10]}")
    incident_id: str = Field(description="Parent incident ID")
    action_id: str = Field(description="ID of the source ActionRecommendation")
    title: str
    description: str
    category: ActionCategory
    priority: ActionPriority
    mode: ActionExecutionMode = Field(default=ActionExecutionMode.ADVISORY)
    status: ResponseActionStatus = Field(default=ResponseActionStatus.RECOMMENDED)
    target_entity: Optional[str] = None
    reason: Optional[str] = None
    supporting_evidence_ids: List[str] = Field(default_factory=list)

    # Lifecycle timestamps
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    acknowledged_at: Optional[datetime] = None
    executed_at: Optional[datetime] = None
    completed_at: Optional[datetime] = None

    # Immutable audit trail
    audit_trail: List[ResponseAuditEvent] = Field(default_factory=list)

    # Simulation output — only populated for SIMULATED mode executions
    simulation_output: Optional[Dict[str, Any]] = None

    model_config = ConfigDict(use_enum_values=True)


class ActionRecommendation(BaseModel):
    """Source advisory recommendation produced by the PlaybookGenerator."""
    id: str = Field(default_factory=lambda: f"act_{uuid4().hex[:8]}")
    title: str = Field(description="Short action summary")
    description: str = Field(description="Step-by-step guidance for the security analyst or end user")
    category: ActionCategory
    priority: ActionPriority
    target_entity: Optional[str] = Field(default=None, description="Entity to apply action on (e.g. IP, URL, user)")
    automated_capability: bool = Field(
        default=False,
        description="Whether this action can be executed via security playbook API (default False: advisory)"
    )
    mode: str = Field(default="ADVISORY", description="Operational execution mode: ADVISORY or SIMULATED")
    reason: Optional[str] = Field(default=None, description="Detailed justification for action recommendation")
    supporting_evidence_ids: List[str] = Field(default_factory=list, description="IDs of evidence items triggering this recommendation")

    @property
    def action(self) -> str:
        return self.title

    model_config = ConfigDict(use_enum_values=True)


class ExecuteActionRequest(BaseModel):
    """API request body to dispatch/transition a response action."""
    mode: ActionExecutionMode = Field(
        default=ActionExecutionMode.SIMULATED,
        description="SIMULATED guarantees zero external impact. ADVISORY logs analyst intent only."
    )
    actor: str = Field(default="Security Analyst", description="Name or role of analyst dispatching action")
    note: Optional[str] = Field(default=None, description="Optional dispatch note from analyst")


class ActionTransitionRequest(BaseModel):
    """API request body for explicit state transitions (acknowledge, dismiss, complete, etc.)."""
    target_status: ResponseActionStatus = Field(description="Desired target lifecycle state")
    actor: str = Field(default="Security Analyst")
    note: Optional[str] = None
